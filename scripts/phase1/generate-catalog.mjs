import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { registry, root, slideTemplate, sampleDeck } from './phase1-lib.mjs'

const check = process.argv.includes('--check')
const outputs = new Map()
const categories = { presentation: '構成・本文', logic: '比較・論理', information: '情報整理', analysis: '図・分析', planning: '計画', structure: '構造' }
for (const layout of registry) {
  const template = slideTemplate(layout)
  outputs.set(layout.template, template)
  outputs.set(`catalog/layouts/${layout.id}.md`, `<!-- Generated by npm run catalog; edit packages/core/registry/layouts.json -->
# ${layout.name} / \`${layout.id}\`

${layout.description}

カテゴリ: ${categories[layout.category]}

![${layout.name}の実ブラウザプレビュー](../previews/${layout.id}.png)

## コピーして使う

Corporateデッキの末尾へ、そのまま貼り付けてください。[初回セットアップ](../../docs/phase1/phase1-usage.md)。

[Markdownファイル](../templates/${layout.id}.md)

\`\`\`\`md
${template.trimEnd()}
\`\`\`\`

## 設定・情報量

- Variant: ${layout.variants.map(v => `\`${v}\``).join(', ')}（既定: \`${layout.variants[0]}\`）
- Density: ${layout.density.map(v => `\`${v}\``).join(', ')}（既定: \`normal\`）
- 情報量目安: ${layout.content_guide}
- 名前付きslot: ${layout.slots.length ? layout.slots.map(s => `\`${s.name}\`（${s.required ? '必須' : '任意'}: ${s.description}）`).join(', ') : 'なし。本文をそのまま使用'}

## 注意点

${layout.notes.map(n => `- ${n}`).join('\n')}

## AI向けメタデータ

以下は人間向けカタログと同じレジストリから生成しています。AIなしで利用できます。

\`\`\`json
${JSON.stringify(Object.fromEntries(Object.entries(layout).filter(([key]) => key !== 'markdown')), null, 2)}
\`\`\`
`)
}
outputs.set('catalog/README.md', `<!-- Generated by npm run catalog -->
# レイアウトカタログ

**Write content. Let design happen.**

10レイアウトのプレビュー・コピペ例・設定・AI用メタデータです。[使い方](../docs/phase1/phase1-usage.md) / [サンプルデッキ](../examples/phase1/slides.md)。

本文は標準Markdown、表、画像、MermaidとSlidevの名前付きslotだけで記述します。プレビュー画像は実ブラウザから生成しています。

${Object.entries(categories).map(([category, name]) => {
  const layouts = registry.filter(l => l.category === category)
  return layouts.length ? `## ${name}\n\n| ID | 名前 | 用途 |\n|---|---|---|\n${layouts.map(l => `| [${l.id}](layouts/${l.id}.md) | ${l.name} | ${l.description} |`).join('\n')}\n` : ''
}).filter(Boolean).join('\n')}
## 更新方法

唯一の定義元は [レジストリ](../packages/core/registry/layouts.json) と [JSON Schema](../packages/core/registry/layouts.schema.json) です。生成物を直接編集せず、\`npm run catalog\` を実行してください。\`npm run catalog:check\` が差分を検出します。画像は \`npm run phase1:browser\` で再生成します。
`)
outputs.set('examples/phase1/slides.md', sampleDeck())
let failed = false
for (const [file, content] of outputs) {
  const path = join(root, file)
  if (check) {
    let actual
    try { actual = readFileSync(path, 'utf8') } catch {}
    if (actual !== content) { console.error(`Out of date: ${file}`); failed = true }
  } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, content) }
}
if (failed) process.exitCode = 1
else console.log(`${outputs.size} catalog files ${check ? 'verified' : 'generated'}`)
