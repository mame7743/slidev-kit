import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const outputFile = join(root, 'docs/layout-inventory.md')
const registry = JSON.parse(readFileSync(join(root, 'packages/theme/registry/layouts.json'), 'utf8'))
const registryById = new Map(registry.map(layout => [layout.id, layout]))
const check = process.argv.includes('--check')

const activeDir = join(root, 'packages/theme/layouts')
const extrasDir = join(activeDir, 'extras')
const activeFiles = readdirSync(activeDir, { withFileTypes: true })
  .filter(entry => entry.isFile() && entry.name.endsWith('.vue'))
  .map(entry => join(activeDir, entry.name))
const extrasFiles = readdirSync(extrasDir, { withFileTypes: true })
  .filter(entry => entry.isFile() && entry.name.endsWith('.vue'))
  .map(entry => join(extrasDir, entry.name))
const filesById = new Map([...activeFiles, ...extrasFiles].map(file => [file.split('/').at(-1).replace(/\.vue$/, ''), file]))

for (const layout of registry) {
  if (!filesById.has(layout.id)) throw new Error(`registry layout has no implementation: ${layout.id}`)
  if (filesById.get(layout.id).startsWith(extrasDir)) throw new Error(`registry layout is under extras/: ${layout.id}`)
}
for (const file of activeFiles) {
  const id = file.split('/').at(-1).replace(/\.vue$/, '')
  if (!registryById.has(id)) throw new Error(`active layout is missing from registry: ${id}`)
}

function implementation(file) {
  const source = readFileSync(file, 'utf8')
  const usesKitSlide = /\bKitSlide\b/.test(source)
  const usesLegacy = /(?:\.\.\/)+(?:interface\/|components\/templates\/)/.test(source)
  if (usesKitSlide && usesLegacy) return 'hybrid'
  if (usesKitSlide) return 'KitSlide専用'
  return '旧interface'
}
function link(path, label = 'あり') {
  if (!path || !existsSync(join(root, path))) return 'なし'
  return `[${label}](../${path})`
}
function row(id) {
  const item = registryById.get(id)
  const file = filesById.get(id)
  const displayName = item ? `\`${id}\`（${item.name}）` : `\`${id}\``
  const filePath = relative(root, file)
  return `| ${displayName} | ${item ? 'あり' : 'なし'} | [\`${filePath}\`](../${filePath}) | ${implementation(file)} | ${link(item?.template)} | ${link(item?.preview)} | ${item ? '公開（registry）' : 'extras（registry外）'} |`
}

const ids = [...registry.map(layout => layout.id), ...extrasFiles.map(file => file.split('/').at(-1).replace(/\.vue$/, '')).sort()]
const content = `<!-- Generated by npm run inventory; do not edit directly. -->
# レイアウト判定表

この表が、レイアウトの公開状態と実装種別を判断する唯一の正です。\`packages/theme/registry/layouts.json\`、レイアウト実体、\`catalog/\` の実在ファイルから自動生成します。

| layout名 | registry | 実体ファイル | 実装種別 | サンプルMarkdown | preview画像 | 状態 |
|---|---|---|---|---|---|---|
${ids.map(row).join('\n')}

- **KitSlide専用**: \`KitSlide.vue\` だけで描画する公開レイアウト。
- **hybrid**: Kit presetでは \`KitSlide.vue\`、その他のvariantでは旧interfaceまたは旧templateを使うレイアウト。
- **旧interface**: KitSlideを使わないregistry外レイアウト。\`extras/\` はregistry・catalog対象外ですが、Slidevのlayouts再帰走査によるbasename登録で手書き利用でき、既存テストでも使用します。catalogサンプルとpreviewは生成しません。

## 更新方法

1. registry・レイアウト・catalogを変更する。
2. \`npm run inventory\` を実行する。
3. \`npm run inventory:check\` で生成結果を確認する。
`

if (check) {
  let actual
  try { actual = readFileSync(outputFile, 'utf8') } catch {}
  if (actual !== content) {
    console.error('Out of date: docs/layout-inventory.md')
    process.exitCode = 1
  } else console.log('layout inventory verified')
} else {
  mkdirSync(dirname(outputFile), { recursive: true })
  writeFileSync(outputFile, content)
  console.log('docs/layout-inventory.md generated')
}
